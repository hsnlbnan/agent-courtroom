export const DICTS: Record<Lang, Dict> = { en, tr };

/** Role name in the current language; unknown roles keep the server's label. */
export const roleName = (t: Dict, role: string, fallback?: string) => t.roles[role] ?? fallback ?? role;

/** A member's name in the current language, from a case's bench (custom members keep their label). */
export const memberName = (t: Dict, members: { role: string; label: string }[], role: string) =>
  roleName(t, role, members.find((m) => m.role === role)?.label);
/** A vote word in the current language (`conditional` → "koşullu"). */
export const voteName = (t: Dict, vote: string) => t.votes[vote] ?? vote;
/** A vote with its confidence, e.g. "koşullu 0.70"; empty when there is no vote. */
export const voteText = (t: Dict, v: { vote: string; confidence: number | null } | null | undefined) =>
  (v?.vote ? `${voteName(t, v.vote)}${v.confidence != null ? ` ${Number(v.confidence).toFixed(2)}` : ''}` : '');

/** A reply reference as people read it: `O-skeptic` becomes "Skeptic's opening"; T3 and U2 stay as they are. */
export const refLabel = (t: Dict, key: string, name: (role: string) => string) => {
  const o = key.match(/^O-(.+)$/);
  return o ? t.refOpening(name(o[1])) : key;
};
/** A note from the server: translated when it carries a known code. */
export const noteText = (t: Dict, n: { text: string; code?: string; params?: P }) => {
  const f = n.code ? t.notes[n.code] : undefined;
  if (!f) return n.text;
  const p = { ...n.params };
  if (typeof p.role === 'string') p.role = roleName(t, p.role);
  return f(p);
};

const KEY = 'council-lang';
const Ctx = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({ lang: 'en', t: en, setLang: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');
  useEffect(() => {
    let saved: string | null = null;
    try { saved = localStorage.getItem(KEY); } catch {}
    setLangState(saved === 'tr' || saved === 'en' ? saved : navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en');
  }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(KEY, l); } catch {}
  }, []);
  const value = useMemo(() => ({ lang, t: DICTS[lang], setLang }), [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useT = () => useContext(Ctx);

/** Fallback text for the 3D scene's error boundary (a class component). */
export function SceneFailed() {
  const { t } = useT();
  return <p className="no-scene">{t.sceneFailed}</p>;
}
