#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.md at the repo root: every production dependency of the web UI
// (the code that is bundled into web/out/ and shipped in the npm package), with its licence
// and the licence text it ships. The app server (app/) has no runtime dependencies.
// It lists the whole production tree, a superset of what the static export bundles.
//
// usage: node web/scripts/notices.mjs   (run after `npm --prefix web ci`)
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(WEB, '..', 'THIRD-PARTY-NOTICES.md');

const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], { cwd: WEB, encoding: 'utf8', maxBuffer: 64 << 20 }));
const pkgs = new Map();
const walk = (deps) => {
  for (const [name, d] of Object.entries(deps ?? {})) {
    if (!d.version || !d.path) continue;
    const key = `${name}@${d.version}`;
    if (pkgs.has(key)) continue;
    pkgs.set(key, { name, version: d.version, path: d.path });
    walk(d.dependencies);
  }
};
walk(tree.dependencies);

const licenceOf = (meta) => {
  const l = meta.license ?? meta.licenses;
  if (typeof l === 'string') return l;
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(' OR ');
  return l?.type ?? 'UNKNOWN';
};
const textOf = (dir) => {
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n));
  return f ? readFileSync(join(dir, f), 'utf8').trim() : null;
};
const noticeOf = (dir) => {
  const f = readdirSync(dir).find((n) => /^notice(\.(md|txt))?$/i.test(n));
  return f ? readFileSync(join(dir, f), 'utf8').trim() : null;
};

const rows = [...pkgs.values()]
  .filter((p) => existsSync(join(p.path, 'package.json')))
  .map((p) => {
    const meta = JSON.parse(readFileSync(join(p.path, 'package.json'), 'utf8'));
    const text = textOf(p.path);
    // A package.json without a licence field still ships its licence file; read the name from it.
    let licence = licenceOf(meta);
    if (licence === 'UNKNOWN' && /^(the )?mit license/i.test(text ?? '')) licence = 'MIT (from its LICENSE file)';
    return { ...p, licence, text, notice: noticeOf(p.path), repo: meta.repository?.url ?? meta.repository ?? meta.homepage ?? '' };
  })
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const counts = rows.reduce((m, r) => m.set(r.licence, (m.get(r.licence) ?? 0) + 1), new Map());
const lines = [
  '# Third-party notices',
  '',
  'agent-courtroom is MIT licensed (see `LICENSE`). Its web UI, shipped prebuilt in `web/out/`, includes code from the',
  'open-source packages below. Each is used under its own licence, reproduced here as the package ships it.',
  'The local server (`app/`) uses only Node.js built-ins.',
  '',
  `Generated by \`node web/scripts/notices.mjs\` from the production dependency tree of \`web/\` (${rows.length} packages).`,
  'The tree is listed whole, so it is a superset of what ships: Next.js build-time and image-optimisation packages',
  '(`sharp`, `@img/*` including the LGPL `libvips` binary, `detect-libc`, `caniuse-lite`, `baseline-browser-mapping`) are',
  'not part of `web/out/` and are not distributed in the npm package (checked 2026-10-31 by searching `web/out/`).',
  '',
  '| Licence | Packages |',
  '|---|---|',
  ...[...counts].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`),
  '',
  '## Packages',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.licence} |`),
  '',
  '## Licence texts',
  '',
];
for (const r of rows) {
  lines.push(`### ${r.name} ${r.version}`, '', `Licence: ${r.licence}${r.repo ? ` · ${String(r.repo).replace(/^git\+/, '')}` : ''}`, '');
  if (r.notice) lines.push('NOTICE:', '', '```', r.notice, '```', '');
  lines.push(r.text ? ['```', r.text, '```'].join('\n') : '_The package ships no licence file; its package.json declares the licence above._', '');
}
writeFileSync(OUT, `${lines.join('\n').trimEnd()}\n`);
const unknown = rows.filter((r) => r.licence === 'UNKNOWN').map((r) => r.name);
console.log(`wrote ${OUT}: ${rows.length} packages; ${[...counts].map(([l, n]) => `${l} ${n}`).join(', ')}${unknown.length ? `; UNKNOWN: ${unknown.join(', ')}` : ''}`);
